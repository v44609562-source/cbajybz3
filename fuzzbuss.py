# Проходим циклом по числам от 1 до 100
for i in range(1, 101):
    
    # 1. Сначала проверяем самое сложное условие (оба числа)
    if i % 3 == 0 and i % 5 == 0:
        print("FizzBuzz")
    
    # 2. Если первое не подошло, проверяем делимость на 3
    elif i % 3 == 0:
        print("Fizz")
    
    # 3. Если и это нет, проверяем на 5
    elif i % 5 == 0:
        print("Buzz")
    
    # 4. Если ни одно условие не сработало — просто выводим число
    else:
        print(i)
