# Программа 2: Калькулятор достижения цели

print("=== КАЛЬКУЛЯТОР ФИНАНСОВЫХ ЦЕЛЕЙ ===\n")

# Ввод данных
goal = int(input("Твоя цель дохода ($/месяц): "))
current = int(input("Текущий доход ($/месяц): "))
monthly_growth = int(input("Планируемый рост ($/месяц): "))

# Расчёты
needed = goal - current
months = needed / monthly_growth
years = months / 12

# Вывод результатов
print("\n=== АНАЛИЗ ===")
print("Нужно заработать ещё:", needed, "$")
print("Достигнешь цели через:", round(months, 1), "месяцев")
print("Это примерно", round(years, 1), "года(лет)")

# Оценка реалистичности
print("\n=== ОЦЕНКА ===")
if years <= 2:
    print("✅ Отличная цель! Вполне достижимо.")
elif years <= 4:
    print("⚡ Амбициозно, но реально при упорстве.")
else:
    print("🔥 Очень амбициозно! Потребуется максимум усилий.")

# Мотивация
total_hours = months * 30 * 4  # месяцы * дни * часы в день
print("\nПри 4 часах учёбы в день потребуется:", int(total_hours), "часов")
print("Начинай прямо сейчас! 💪")